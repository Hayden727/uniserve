"""Replay immutable native Conv3d taps through standalone and captured calls."""

import pytest
import torch

from tests.python.integration.runtime.native_reference import (
    load_case,
    reference_root,
)
from uniserve.nn.convolution import Conv3d
from uniserve.runtime import CUDAGraph, ExecutionContext

pytestmark = [pytest.mark.integration, pytest.mark.gpu]


@pytest.mark.parametrize("name", ["wan_vsa_plucker", "wan_vsa_ucpe"])
@torch.inference_mode()
def test_torch_unfold_matches_native_saved_convolution(name):
    fields, case = load_case(reference_root(), name)
    assert case["kind"] == "wan_vsa_model"
    weight = fields["weight.patch_embedding.proj.weight"]
    bias = fields["weight.patch_embedding.proj.bias"]
    values = fields["sample"].cuda()
    expected = fields["tap.0.patch_embedding.proj"].cuda()
    layer = Conv3d(
        weight.shape[1],
        weight.shape[0],
        weight.shape[2:],
        stride=weight.shape[2:],
        device="meta",
        dtype=weight.dtype,
        backend="torch_unfold",
    )
    layer.weight = torch.nn.Parameter(weight.cuda(), requires_grad=False)
    layer.bias = torch.nn.Parameter(bias.cuda(), requires_grad=False)
    # These comparisons are exact native numerical contracts, not a newly
    # selected tolerance or a reference regenerated by the candidate stack.
    torch.testing.assert_close(layer(values), expected, rtol=0, atol=0)
    with ExecutionContext(layer, convolution=()) as context:
        context.prepare(None)
        torch.testing.assert_close(layer(values), expected, rtol=0, atol=0)
        output = torch.empty_like(expected)
        with CUDAGraph(context=context) as graph:
            graph.capture(lambda: output.copy_(layer(values)))
            values.zero_()
            graph.replay()
            torch.testing.assert_close(
                output,
                layer.bias[None, :, None, None, None].expand_as(output),
                rtol=0,
                atol=0,
            )
            values.copy_(fields["sample"])
            graph.replay()
            torch.testing.assert_close(output, expected, rtol=0, atol=0)
